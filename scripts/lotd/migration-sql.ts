// The Zone / Stage / ZoneWalk rows for lotd26, generated from rooms.ts as an
// idempotent sync, the same shape as scripts/lgw/migration-sql.ts. Any
// change to a room's zone or address, or anything that moves the walking
// times, ships as a new migration carrying a fresh `--sql` block, and
// zones.test.ts fails if the latest such block differs from what this
// generates now.
//
// A Stage that already exists only gets its zone and address brought up to
// date: names and order stay whatever /admin last set. Removing a room or a
// zone would need a DELETE, written by hand in that migration.
import { ROOMS, ZONES } from "./rooms";
import { walkFromTicketDesk, zoneWalkRows } from "./zones";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export const SQL_BEGIN = "-- BEGIN generated by `npm run import:lotd -- --sql`; do not edit by hand.";
export const SQL_END = "-- END generated";

/** "witte-de-with" -> "witt": the ZoneWalk id scheme the first lotd26 migration used. */
export const walkIdPart = (zoneSlug: string) => zoneSlug.replace(/-/g, "").slice(0, 4);

export function buildStructureSql(): string {
  const fromDesk = walkFromTicketDesk();
  const zoneRows = ZONES.map(
    (z, i) => `  (${q(`lotd26-z-${z.slug}`)}, 'lotd26', ${q(z.name)}, ${q(z.slug)}, ${i}, ${fromDesk.get(z.slug)})`,
  );

  const stageRows = ROOMS.map(
    (r, i) =>
      `  (${q(`lotd26-${r.slug}`)}, 'lotd26', ${q(`lotd26-z-${r.zone}`)}, ${q(r.name)}, ${q(r.slug)}, ${q(r.address)}, ${i}, CURRENT_TIMESTAMP)`,
  );

  const walkRows = zoneWalkRows().map(
    (w) =>
      `  (${q(`lotd26-w-${walkIdPart(w.from)}-${walkIdPart(w.to)}`)}, ${q(`lotd26-z-${w.from}`)}, ${q(`lotd26-z-${w.to}`)}, ${w.minutes})`,
  );

  return [
    SQL_BEGIN,
    'INSERT INTO "Zone" ("id", "festivalId", "name", "slug", "order", "walkMinutesFromHub")',
    "VALUES",
    zoneRows.join(",\n"),
    'ON CONFLICT ("id") DO UPDATE SET "name" = EXCLUDED."name", "order" = EXCLUDED."order", "walkMinutesFromHub" = EXCLUDED."walkMinutesFromHub";',
    "",
    'INSERT INTO "Stage" ("id", "festivalId", "zoneId", "name", "slug", "address", "order", "updatedAt")',
    "VALUES",
    stageRows.join(",\n"),
    'ON CONFLICT ("id") DO UPDATE SET "zoneId" = EXCLUDED."zoneId", "address" = EXCLUDED."address", "updatedAt" = CURRENT_TIMESTAMP;',
    "",
    'INSERT INTO "ZoneWalk" ("id", "fromZoneId", "toZoneId", "minutes")',
    "VALUES",
    walkRows.join(",\n"),
    'ON CONFLICT ("id") DO UPDATE SET "minutes" = EXCLUDED."minutes";',
    SQL_END,
  ].join("\n");
}
